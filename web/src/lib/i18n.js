import { useStore } from './store'

// 多语言支持：以简体中文原文作为翻译 key（zh-CN 恒等返回原文）。
// 支持占位符：t('{n} 个文件', { n: 3 })；语言偏好存 localStorage，默认跟随浏览器语言、兜底简体中文。
const KEY = 'r2x-lang'

export const LANGS = [
  { code: 'zh-CN', label: '简体中文' },
  { code: 'zh-TW', label: '繁體中文' },
  { code: 'en', label: 'English' },
  { code: 'ja', label: '日本語' },
  { code: 'ko', label: '한국어' },
]

export function setLang(code) {
  const valid = LANGS.some((l) => l.code === code) ? code : 'zh-CN'
  localStorage.setItem(KEY, valid)
  useStore.getState().setLang(valid)
}

export function t(str, params) {
  const lang = useStore.getState().lang
  let out = str
  if (lang !== 'zh-CN') {
    const dict = DICTS[lang]
    if (dict && dict[str]) out = dict[str]
  }
  if (params) {
    for (const k in params) out = out.split('{' + k + '}').join(String(params[k]))
  }
  return out
}

// 组件内使用：订阅 store 中的 lang，语言切换时触发重渲染
export function useT() {
  useStore((s) => s.lang)
  return t
}

